import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, readFile, stat, unlink, rmdir } from 'node:fs/promises';
import { resolve, join, dirname } from 'node:path';
import { saveDesktopExportDirectory, prepareDesktop, cleanupAllDesktop, desktopExportInfo, clearDesktopExports, beginEml, appendEml, finishEml } from '../helper/desktop-export.mjs';

test('exports survive disconnect and clearing preserves unrelated and incomplete files', async () => {
  const root = await mkdtemp(resolve('work/retention-test-'));
  const original = process.env.LOCALAPPDATA;
  process.env.LOCALAPPDATA = root;
  const exports = join(root, 'exports');
  await mkdir(exports);
  try {
    await saveDesktopExportDirectory(exports);
    const options = { identity: '<stable@example.test>', target: 'chatgpt', format: 'txt', mail: { body: 'First' } };
    const first = await prepareDesktop(options, AbortSignal.abort());
    const quoted = await prepareDesktop({ ...options, includeQuotes: true, mail: { body: 'Quoted' } }, AbortSignal.abort());
    assert.equal(dirname(first.path), dirname(quoted.path));
    assert.notEqual(first.path, quoted.path);
    const repeated = await prepareDesktop({ ...options, mail: { body: 'Replacement' } }, AbortSignal.abort());
    assert.equal(first.path, repeated.path);
    assert.match(await readFile(first.path, 'utf8'), /Replacement/);
    assert.match(await readFile(quoted.path, 'utf8'), /Quoted/);
    const eml1 = await beginEml({ ...options, size: 3 });
    assert.equal(dirname(eml1.path), dirname(first.path));
    await appendEml({ token: eml1.token, offset: 0, base64: 'YWJj' });
    await finishEml({ token: eml1.token }, AbortSignal.abort());
    const eml2 = await beginEml({ ...options, size: 3 });
    assert.equal(eml1.path, eml2.path);
    assert.equal(await readFile(eml1.path, 'utf8'), 'abc');
    await assert.rejects(prepareDesktop(options, AbortSignal.abort()));
    await cleanupAllDesktop();
    assert.equal(await readFile(eml1.path, 'utf8'), 'abc');
    assert.equal((await desktopExportInfo()).count, 3);
    await clearDesktopExports({ path: exports });
    const result = await prepareDesktop({ target: 'chatgpt', format: 'txt', mail: { body: 'Keep this message' } }, AbortSignal.abort());
    await cleanupAllDesktop();
    assert.match(await readFile(result.path, 'utf8'), /Keep this message/);
    const unrelated = join(exports, 'keep.txt');
    await writeFile(unrelated, 'keep');
    const extra = join(dirname(result.path), 'keep.txt');
    await writeFile(extra, 'keep');
    const pending = await beginEml({ target: 'chatgpt', size: 3 });
    assert.equal((await desktopExportInfo()).count, 1);
    assert.ok((await desktopExportInfo()).bytes > 0);
    await assert.rejects(clearDesktopExports({ path: root }));
    assert.equal((await clearDesktopExports({ path: exports })).count, 0);
    await assert.rejects(stat(result.path), { code: 'ENOENT' });
    assert.equal(await readFile(extra, 'utf8'), 'keep');
    assert.equal(await readFile(unrelated, 'utf8'), 'keep');
    await assert.rejects(stat(pending.path), { code: 'ENOENT' });
    await appendEml({ token: pending.token, offset: 0, base64: 'YWJj' });
    await finishEml({ token: pending.token }, AbortSignal.abort());
    await cleanupAllDesktop();
    assert.equal(await readFile(pending.path, 'utf8'), 'abc');
    assert.equal((await desktopExportInfo()).bytes, 3);
    await clearDesktopExports({ path: exports });
    await assert.rejects(stat(dirname(pending.path)), { code: 'ENOENT' });
    await unlink(extra); await rmdir(dirname(result.path));
    await unlink(unrelated); await rmdir(exports);
    await unlink(join(root, 'MailAiAssist', 'export-settings.json'));
    await rmdir(join(root, 'MailAiAssist')); await rmdir(root);
  } finally { process.env.LOCALAPPDATA = original; }
});
